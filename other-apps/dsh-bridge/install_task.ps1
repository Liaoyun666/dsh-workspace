# install_task.ps1 - register / unregister the DshFishBridge scheduled task.
# Idempotent: safe to run repeatedly. Runs as the current user, no admin needed.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File install_task.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File install_task.ps1 -Uninstall

[CmdletBinding()]
param(
    [switch]$Uninstall,
    [string]$TaskName = "DshFishBridge",
    [string]$BridgeDir = $PSScriptRoot
)

$ErrorActionPreference = "Stop"

function Find-Pythonw {
    $cand = @(
        "$env:LOCALAPPDATA\Programs\Python\Python310\pythonw.exe",
        "$env:LOCALAPPDATA\Programs\Python\Python311\pythonw.exe",
        "$env:LOCALAPPDATA\Programs\Python\Python312\pythonw.exe"
    )
    foreach ($c in $cand) { if (Test-Path $c) { return $c } }
    $py = (Get-Command py.exe -ErrorAction SilentlyContinue)
    if ($py) {
        $out = & py -3 -c "import sys;print(sys.executable)" 2>$null
        if ($out) {
            $w = Join-Path (Split-Path $out) "pythonw.exe"
            if (Test-Path $w) { return $w }
            if (Test-Path $out) { return $out }
        }
    }
    $pw = (Get-Command pythonw.exe -ErrorAction SilentlyContinue)
    if ($pw) { return $pw.Source }
    throw "pythonw.exe not found"
}

$existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue

if ($Uninstall) {
    if ($existing) {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Write-Host "uninstalled: $TaskName"
    } else {
        Write-Host "not installed: $TaskName"
    }
    return
}

$pythonw = Find-Pythonw
$worker = Join-Path $BridgeDir "worker.py"
if (-not (Test-Path $worker)) { throw "worker.py not found in $BridgeDir" }

# --- hidden-window launcher -------------------------------------------------
# wscript + WScript.Shell.Run(..., 0, False) => no console window at all.
# The VBS resolves worker.py relative to its own location, so the Chinese path
# in BridgeDir never has to be embedded here (the file stays pure ASCII).
$vbs = Join-Path $BridgeDir "start_hidden.vbs"
$vbsBody = @"
' auto-generated by install_task.ps1 - starts the DshFishBridge worker without a console window
Option Explicit
Dim sh, fso, here, pyw, worker
Set sh = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
here = fso.GetParentFolderName(WScript.ScriptFullName)
sh.CurrentDirectory = here
pyw = "$pythonw"
If Not fso.FileExists(pyw) Then pyw = "pythonw.exe"
worker = here & "\worker.py"
sh.Run Chr(34) & pyw & Chr(34) & " -X utf8 " & Chr(34) & worker & Chr(34), 0, False
"@
[System.IO.File]::WriteAllText($vbs, $vbsBody, (New-Object System.Text.ASCIIEncoding))

if ($existing) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    Write-Host "removed previous definition of $TaskName"
}

# Trigger 1: at user logon.  Trigger 2: repeat every 5 minutes (self-healing;
# the named mutex inside worker.py stops a second instance from doing work).
$tLogon = New-ScheduledTaskTrigger -AtLogOn -User "$env:USERDOMAIN\$env:USERNAME"
$tRepeat = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes 5) -RepetitionDuration (New-TimeSpan -Days 3650)

$action = New-ScheduledTaskAction -Execute "wscript.exe" -Argument ('"' + $vbs + '"') -WorkingDirectory $BridgeDir

$settings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Seconds 0) -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)

$principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive -RunLevel Limited

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger @($tLogon, $tRepeat) -Settings $settings -Principal $principal -Description "DshFishBridge: pull jobs from the cloud AstrBot queue and run them in local DSH" | Out-Null

# The DSH headless sandbox rewrites the DACL of its workspace before every shell
# call (grantWrite). A workspace that only inherits "Authenticated Users:(M)"
# denies that with Win32 5 and breaks every pwsh/bash call inside the job, so
# make sure the jobs root carries an explicit Full Control ACE for this user.
$jobsRoot = "E:/工作区/肥鱼之家/jobs"
New-Item -ItemType Directory -Force -Path $jobsRoot | Out-Null
$me = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
icacls.exe "E:/工作区/肥鱼之家" /grant ($me + ":(OI)(CI)F") /T 2>&1 | Out-Null
Write-Host "jobs root ready: $jobsRoot (explicit Full Control granted to $me)"

Write-Host "installed: $TaskName"
Write-Host "  pythonw : $pythonw"
Write-Host "  worker  : $worker"
Write-Host "  launcher: $vbs"

Start-ScheduledTask -TaskName $TaskName
Start-Sleep -Seconds 2
Get-ScheduledTask -TaskName $TaskName | Select-Object TaskName, State | Format-List
Get-ScheduledTaskInfo -TaskName $TaskName | Select-Object LastRunTime, LastTaskResult, NumberOfMissedRuns | Format-List
